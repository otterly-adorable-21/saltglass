/* Music player: floating play button + soundtrack modal (like the Velvet Haven site).
   The site is one page, so the music never restarts when visitors change views. */
(function (SG) {
  const { $, $$, esc } = SG, S = SG.sound;
  const FILES = (window.TRACKS || []).filter(t => t && t.src && t.name);
  const TRACKS = FILES.map((t, i) => ({ id: 'f' + i, name: t.name, src: t.src, by: t.by || '' })).concat([{ id: 'ambient', name: 'Tideglass (built-in ambience)', by: 'Generated by the site', ambient: true }]);
  const K = { track: 'sg_track', time: 'sg_time', play: 'sg_playing', vol: 'sg_vol', fx: 'sg_fx' };
  const get = k => { try { return localStorage.getItem(k); } catch (e) { return null; } };
  const set = (k, v) => { try { localStorage.setItem(k, v); } catch (e) {} };

  const audio = new Audio(); audio.preload = 'none';
  let cur = Math.max(0, TRACKS.findIndex(t => t.id === get(K.track))), playing = false, loaded = -1;
  let vol = parseFloat(get(K.vol)); if (isNaN(vol)) vol = .38; vol = Math.min(1, Math.max(0, vol));
  audio.volume = vol; S.vol = Math.min(1, vol * 1.3);
  S.fx = get(K.fx) === '1';

  /* floating buttons */
  const btn = document.createElement('button'); btn.id = 'audio-btn'; btn.className = 'mbtn'; btn.setAttribute('aria-label', 'Play music'); btn.textContent = '♪';
  const list = document.createElement('button'); list.id = 'playlist-btn'; list.className = 'mbtn'; list.setAttribute('aria-label', 'Choose soundtrack');
  list.innerHTML = '<svg viewBox="0 0 24 24" width="18" height="18" fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round"><path d="M4 6h12M4 12h12M4 18h8"/><circle cx="19" cy="17" r="2.2"/><path d="M21.2 17V8l-4 1"/></svg>';
  document.body.appendChild(btn); document.body.appendChild(list);

  function sync() {
    btn.textContent = playing ? '♬' : '♪'; btn.classList.toggle('playing', playing);
    btn.setAttribute('aria-label', playing ? 'Pause music' : 'Play music');
    const pb = $('#mpPlay'); if (pb) pb.textContent = playing ? 'Pause' : 'Play';
    $$('#mpList .trk').forEach((e, i) => e.classList.toggle('active', i === cur));
    const n = $('#mpNow'); if (n) n.textContent = TRACKS[cur].name;
  }
  function load(i) {
    cur = (i + TRACKS.length) % TRACKS.length; const t = TRACKS[cur]; set(K.track, t.id);
    if (t.ambient) { audio.pause(); } else { if (loaded !== cur) { audio.src = t.src; loaded = cur; } }
    sync(); seekUi();
  }
  function play() {
    const t = TRACKS[cur];
    if (t.ambient) { S.ambient(true); playing = true; set(K.play, '1'); sync(); return; }
    S.ambient(false); if (loaded !== cur) load(cur);
    audio.play().then(() => { playing = true; set(K.play, '1'); sync(); }).catch(() => { playing = false; set(K.play, '0'); sync(); SG.toast('Could not play "' + t.name + '". Check the file name and that it is uploaded.'); });
  }
  function pause() { audio.pause(); S.ambient(false); playing = false; set(K.play, '0'); sync(); }
  const toggle = () => playing ? pause() : play();
  function go(i) { const was = playing; if (was) pause(); load(i); if (was) play(); }
  btn.addEventListener('click', toggle);
  audio.addEventListener('ended', () => { if (TRACKS.length > 1) { load(cur + 1); play(); } });
  audio.addEventListener('error', () => { if (playing && !TRACKS[cur].ambient) { playing = false; sync(); } });
  audio.addEventListener('timeupdate', seekUi);
  audio.addEventListener('loadedmetadata', seekUi);

  /* resume where the visitor left off */
  load(cur);
  const savedTime = parseFloat(get(K.time));
  if (!isNaN(savedTime) && !TRACKS[cur].ambient) audio.addEventListener('loadedmetadata', () => { try { audio.currentTime = savedTime; } catch (e) {} }, { once: true });
  if (get(K.play) === '1') {
    // Browsers block sound until the visitor interacts, so start on their first tap.
    const go1 = () => { removeEventListener('pointerdown', go1); removeEventListener('keydown', go1); if (!playing) play(); };
    addEventListener('pointerdown', go1, { once: true }); addEventListener('keydown', go1, { once: true });
  }
  setInterval(() => { if (!TRACKS[cur].ambient) set(K.time, String(audio.currentTime || 0)); }, 1000);

  /* modal */
  const fmt = s => { if (!isFinite(s)) return '0:00'; const m = Math.floor(s / 60); return m + ':' + String(Math.floor(s % 60)).padStart(2, '0'); };
  function seekUi() {
    const bar = $('#mpSeek'); if (!bar) return;
    const amb = TRACKS[cur].ambient, wrap = $('#mpSeekWrap'); if (wrap) wrap.hidden = amb;
    if (amb) return;
    if (document.activeElement !== bar) bar.value = audio.duration ? (audio.currentTime / audio.duration * 1000) : 0;
    $('#mpT').textContent = fmt(audio.currentTime); $('#mpD').textContent = fmt(audio.duration);
  }
  function open() {
    const body = SG.openModal(`<div class="mp"><h3 class="bm-h" style="text-align:center">The Saltglass Soundtrack</h3>
      <p class="small" style="text-align:center;margin:0 0 14px">Choose what plays while you wander.</p>
      <div class="mp-now"><span class="small-label" style="margin:0">Now selected</span><div id="mpNow" class="mp-title"></div></div>
      <div id="mpSeekWrap" class="mp-seek"><span id="mpT">0:00</span><input type="range" id="mpSeek" min="0" max="1000" value="0" aria-label="Seek"><span id="mpD">0:00</span></div>
      <div class="mp-ctl"><button class="btn" id="mpPrev" aria-label="Previous track">‹ Prev</button><button class="btn on" id="mpPlay">Play</button><button class="btn" id="mpNext" aria-label="Next track">Next ›</button></div>
      <label class="mp-vol">Volume<input type="range" id="mpVol" min="0" max="100" value="${Math.round(vol * 100)}"></label>
      <div class="mp-list" id="mpList">${TRACKS.map((t, i) => `<button class="trk" data-i="${i}"><span class="ti">♪</span><span class="tn">${esc(t.name)}${t.by ? '<em>' + esc(t.by) + '</em>' : ''}</span><span class="ts">Selected</span></button>`).join('')}</div>
      <label class="mp-fx"><input type="checkbox" id="mpFx" ${S.fx ? 'checked' : ''}> Chimes and whale song when I click things</label></div>`);
    $('#mpPlay', body).addEventListener('click', toggle);
    $('#mpPrev', body).addEventListener('click', () => go(cur - 1));
    $('#mpNext', body).addEventListener('click', () => go(cur + 1));
    $$('#mpList .trk', body).forEach(b => b.addEventListener('click', () => go(+b.dataset.i)));
    $('#mpVol', body).addEventListener('input', e => { vol = e.target.value / 100; audio.volume = vol; S.setVolume(Math.min(1, vol * 1.3)); set(K.vol, String(vol)); });
    $('#mpSeek', body).addEventListener('input', e => { if (audio.duration) audio.currentTime = e.target.value / 1000 * audio.duration; });
    $('#mpFx', body).addEventListener('change', e => { S.setFx(e.target.checked); set(K.fx, e.target.checked ? '1' : '0'); });
    sync(); seekUi();
  }
  list.addEventListener('click', open);
})(window.SG);
